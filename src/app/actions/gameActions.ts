import { getProfile, getDailyQuest, updateProfile, updateDailyQuest } from '@/lib/supabaseServer';
import { Profile, DailyQuest } from '@/lib/supabase';

export interface ActionResponse {
  success: boolean;
  message: string;
  data?: any;
}

/**
 * Server Action: Claim Daily Rewards
 * Securely verifies the check-in eligibility on the server side.
 * The client CANNOT forge the current server time or manipulate the reward amount.
 */
export async function claimDailyReward(userId: string): Promise<ActionResponse> {
  try {
    const dailyQuest = await getDailyQuest(userId);
    const lastCheckDate = new Date(dailyQuest.last_login_claim);
    const now = new Date();
    
    // Calculate the difference in milliseconds
    const diffMs = now.getTime() - lastCheckDate.getTime();
    const diffHours = diffMs / (1000 * 60 * 60);

    if (diffHours < 24) {
      const remainingHours = Math.ceil(24 - diffHours);
      return {
        success: false,
        message: `مكافأتك اليومية غير متاحة بعد. يرجى الانتظار ${remainingHours} ساعة أخرى.`,
      };
    }

    // Load profile
    const profile = await getProfile(userId);

    // Update profile gold coins (+50)
    const updatedProfile = {
      ...profile,
      gold_coins: profile.gold_coins + 50,
    };

    // Update last check-in to NOW
    const updatedDailyQuest = {
      ...dailyQuest,
      last_login_claim: now.toISOString(),
    };

    // Write back to DB (Atomic operations/Transactions should be used in production)
    await updateProfile(updatedProfile);
    await updateDailyQuest(updatedDailyQuest);

    return {
      success: true,
      message: 'تم الحصول على المكافأة اليومية! حصلت على +50 عملة ذهبية! 🎉',
      data: updatedProfile,
    };
  } catch (error: any) {
    return {
      success: false,
      message: error.message || 'حدث خطأ أثناء معالجة طلبك.',
    };
  }
}

/**
 * Server Action: Reward Match Outcome
 * Securely processes match endings on the server side.
 * 
 * SECURITY PREVENTING CLIENT-SIDE TAMPERING:
 * ----------------------------------------
 * In a real production environment, calling this function with arbitrary 'outcome' or 'userId' parameters
 * from the client is highly dangerous. To secure this:
 * 1. The client must submit a "gameToken" or "matchId" generated by the backend chess engine when the match starts.
 * 2. This Server Action queries the authoritative game server or database of completed match sessions:
 *    `const gameSession = await db.game_sessions.find(matchId)`
 * 3. The server checks that:
 *    a) The match is actually completed.
 *    b) The logged-in user matches the participant UUID.
 *    c) The match has not already been claimed/rewarded (preventing replay attacks).
 *    d) The actual winner matches the submitted 'outcome'.
 * 
 * For this implementation, we simulate these security validation checks on the server.
 */
export async function rewardMatchOutcome(
  userId: string, 
  outcome: 'win' | 'loss',
  gameToken?: string // Cryptographic verification token
): Promise<ActionResponse> {
  try {
    // SECURITY SIMULATION CHECK:
    // If a production token is provided, verify it. Otherwise, explain or log verification.
    if (gameToken) {
      const isValidToken = verifyGameToken(gameToken, userId, outcome);
      if (!isValidToken) {
        return {
          success: false,
          message: 'فشل التحقق الأمني: رمز المباراة غير صالح أو تم التلاعب به! 🛡️',
        };
      }
    }

    const profile = await getProfile(userId);
    let rewardCoins = 0;
    let newWins = profile.wins;
    let newLosses = profile.losses;

    if (outcome === 'win') {
      rewardCoins = 100;
      newWins += 1;
    } else {
      rewardCoins = 20;
      newLosses += 1;
    }

    const updatedProfile: Profile = {
      ...profile,
      gold_coins: profile.gold_coins + rewardCoins,
      wins: newWins,
      losses: newLosses,
    };

    await updateProfile(updatedProfile);

    return {
      success: true,
      message: outcome === 'win' 
        ? `لقد فزت بالمباراة! حصلت على +100 عملة ذهبية! 🏆` 
        : `لقد خسرت المباراة، شكراً لمشاركتك! حصلت على +20 عملة ذهبية! ⚔️`,
      data: updatedProfile,
    };
  } catch (error: any) {
    return {
      success: false,
      message: error.message || 'حدث خطأ أثناء معالجة مكافأة المباراة.',
    };
  }
}

/**
 * Mock cryptographic token verification function.
 * In production, this would decrypt a JWT or query the authoritative game server.
 */
function verifyGameToken(token: string, userId: string, outcome: string): boolean {
  // Real implementation: jwt.verify(token, process.env.GAME_SERVER_SECRET)
  // For safety simulation, we verify it is formatted correctly as 'valid-token-<userId>-<outcome>'
  return token === `valid-token-${userId}-${outcome}`;
}

/**
 * Resets the daily check-in to allow easy testing of claiming daily rewards.
 */
export async function resetDailyCheckTime(userId: string): Promise<ActionResponse> {
  try {
    // Set last check-in to 25 hours ago
    const yesterday = new Date(Date.now() - 25 * 60 * 60 * 1000).toISOString();
    await updateDailyQuest({
      user_id: userId,
      last_login_claim: yesterday,
      matches_played_today: 0,
    });
    return {
      success: true,
      message: 'تمت إعادة تعيين مكافأة الدخول اليومي! يمكنك المطالبة بها الآن.',
    };
  } catch (error: any) {
    return {
      success: false,
      message: error.message,
    };
  }
}

/**
 * Fetch profile data securely on server.
 */
export async function fetchUserProfile(userId: string): Promise<Profile> {
  return await getProfile(userId);
}

export async function fetchDailyCheck(userId: string): Promise<any> {
  const quest = await getDailyQuest(userId);
  return {
    user_id: quest.user_id,
    last_check_in: quest.last_login_claim,
    matches_played_today: quest.matches_played_today,
  };
}

/**
 * Server Action: processEstimationBuyIn
 */
export async function processEstimationBuyIn(userId: string): Promise<ActionResponse> {
  try {
    const profile = await getProfile(userId);
    if (profile.gold_coins < 50) {
      return { success: false, message: 'ليس لديك ذهب كافٍ للمشاركة! 🪙' };
    }
    const updatedProfile = {
      ...profile,
      gold_coins: profile.gold_coins - 50,
    };
    await updateProfile(updatedProfile);
    return { success: true, message: 'تم دفع رسوم دخول الكازينو: -50 ذهبة 🎰', data: updatedProfile };
  } catch (error: any) {
    return { success: false, message: error.message };
  }
}

